@_register(
    "SYN-03",
    "Synonyms are not case or spacing duplicates of each other",
    independent=True,
    severities=(LOW,),
)
def syn03_near_duplicates(ctx: RecordContext) -> Iterator[Finding]:
    items = _synonyms(ctx)
    if items is None:
        return
    lowered = [i.lower() for i in items]
    squashed = {re.sub(r"[\s\-,]", "", i) for i in lowered}
    if len(squashed) < len(lowered):
        yield ctx.finding("SYN-03", LOW, "case/spacing duplicates")


@_register(
    "SYN-04",
    "Synonyms do not contradict the entry's stereochemistry or solvation",
    independent=True,
    severities=(MEDIUM,),
)
def syn04_contradictions(ctx: RecordContext) -> Iterator[Finding]:
    items = _synonyms(ctx)
    if items is None:
        return
    if ctx.specific and not ctx.racemic and any(RACEMIC.search(i) for i in items):
        yield ctx.finding(
            "SYN-04", MEDIUM, "racemic/rel synonyms on an enantiopure entry"
        )
    # `parse` gates the structural half, and only that half: the racemic clause
    # above compares two names and is answerable without a structure. Structure's
    # own docstring says its defaults mean "unknown", not "absent", so reading
    # `water` on a record RDKit could not read calls it anhydrous on no evidence --
    # the record is held by INT-07 either way, but its report then carries a claim
    # the gate never established, and that report is what a chemist works from.
    if (
        ctx.structure.parse
        and not ctx.structure.water
        and any(HYDRATE_WORD.search(i.lower()) for i in items)
    ):
        yield ctx.finding("SYN-04", MEDIUM, "hydrate synonyms on an anhydrous entry")


@_register(
    "SYN-05",
    "Synonym list uses the bare ';' delimiter with no stray whitespace",
    independent=True,
    severities=(LOW,),
)
def syn05_whitespace(ctx: RecordContext) -> Iterator[Finding]:
    if ctx.synonym is None:
        return
    parts = ctx.synonym.split(SYNONYM_DELIMITER)
    if any(p != p.strip() or "  " in p for p in parts):
        yield ctx.finding("SYN-05", LOW, "whitespace oddities")


@_register(
    "SYN-06",
    "Synonyms are not structural identifiers",
    independent=True,
    severities=(MEDIUM,),
)
def syn06_structural_identifiers(ctx: RecordContext) -> Iterator[Finding]:
    """An InChIKey has no digits, so a "looks like a word" filter accepts it.

    Handoff case 14: 42 candidate drug names became 10 once identifiers of this
    shape were excluded, of which 6 were real.
    """
    items = _synonyms(ctx)
    if items is None:
        return
    bad = [i for i in items if INCHIKEY_SHAPED.match(i) or i.startswith("InChI=")]
    if bad:
        yield ctx.finding(
            "SYN-06", MEDIUM, f"structural identifiers as synonyms: {bad[:3]}"
        )


@_register(
    "IUP-01",
    "Systematic name is a name, not a machine-joined component list",
    independent=True,
    severities=(LOW,),
)
def iup01_machine_name(ctx: RecordContext) -> Iterator[Finding]:
    if ctx.iupac and ";" in ctx.iupac:
        yield ctx.finding(
            "IUP-01", LOW, "PubChem machine name (semicolon-joined components)"
        )


def _synonyms(ctx: RecordContext) -> list[str] | None:
    """The synonym list, or None when the field is absent.

    Absent and empty are different: INT-03 reports an absent SYNONYM, and the
    hygiene checks have nothing to say about it.
    """
    if ctx.synonym is None:
        return None
    return [i.strip() for i in ctx.synonym.split(SYNONYM_DELIMITER)]


