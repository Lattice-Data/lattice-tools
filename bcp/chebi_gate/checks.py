# A structural identifier written where a name belongs. An InChIKey is 14 letters,
# a hyphen, 10 letters, a hyphen and one letter -- no digits anywhere -- so a
# "does it look like a word" test accepts it as a drug name. Matched explicitly
# instead.
INCHIKEY_SHAPED = re.compile(r"^[A-Z]{14}-[A-Z]{10}-[A-Z]$")

# A vendor code inside a name, stripped before stereo descriptors are looked for so
# that the "S" of "SB 203580" is not read as an (S) configuration.
VENDOR_CODE = re.compile(
    r"\b(?:RS|L|D|S|R|SR|SDZ|WAY|SB|PD|MRS|CGP|BMS|JNJ|GR|SKF|RU|RJR|TC|NNC|UK|ICI"
    r"|LY|CD|SN|SX|BIO|DS|CO|CH)[ -]?\d"
)

# A name asserting specific stereochemistry, and a name asserting a racemate or
# relative configuration. A name can match both, and then the racemate wins.
SPECIFIC = re.compile(
    r"\(\d*[RSEZ](?:,\d*[RSEZ])*\)|\((?:\+|-)\)"
    r"|\b(?:cis|trans|threo|erythro|exo|endo)\b|(?<![A-Za-z0-9-])[DL]-(?=[A-Za-z(])"
)
RACEMIC = re.compile(
    r"\(\+/-\)|\(\+-\)|\brac\b|\brel-|(?<![A-Za-z0-9])DL-|\(RS\)|\(R\*|\bracemic\b"
)

# Stoichiometry prefix in a salt name, and what each prefix claims.
SALT_WORD = re.compile(
    r"\b(hemi|sesqui|di|tri|tetra|mono)?(hydrochloride|hydrobromide|maleate"
    r"|fumarate|oxalate|iodide|bromide|chloride|sulfate|sulphate|tosylate|mesylate"
    r"|tartrate|napadisylate|sodium salt|potassium salt)"
)
PREFIX_COUNT = {
    None: 1,
    "mono": 1,
    "di": 2,
    "tri": 3,
    "tetra": 4,
    "hemi": 0.5,
    "sesqui": 1.5,
}

# Dibasic acids where both 1:1 and 2:1 are conventional, so a name with no prefix
# asserts nothing about the ratio.
AMBIGUOUS_RATIO_SALTS = ("napadisylate", "sulfate", "sulphate", "oxalate", "tartrate")


# A named solvate, with its optional multiplier prefix. Matched as a word rather
# than as a substring: "ethanol" appears inside ordinary compound names --
# 2-phenylethanol, aminoethanol, any alcohol whose parent chain is ethane -- and a
# substring test reports every one of them as an ethanolate with no ethanol drawn.
# The batch this was ported from happened to contain no such compound, so the
# prototype's `"ethanol" in iupac` never misfired; that is luck, not correctness.
# "hydrate" has the same problem in "dehydrate" and "carbohydrate".
_SOLVATE_PREFIX = r"(?:hemi|mono|di|tri|tetra|penta|hexa|hepta|octa|sesqui)?"
HYDRATE_WORD = re.compile(rf"(?<![a-z]){_SOLVATE_PREFIX}hydrate\b")
# Shared with SYN-04, which had the same bare-substring bug: it fired on a
# synonym reading "carbohydrate derivative" or "sodium dehydrate".
ETHANOLATE_WORD = re.compile(rf"(?<![a-z]){_SOLVATE_PREFIX}ethanolate\b")

# A solvate can also arrive as a standalone component of a PubChem machine name,
# which joins components with ";" and no space.
HYDRATE_COMPONENTS = frozenset({"hydrate", "water", "oxidane"})
ETHANOLATE_COMPONENTS = frozenset({"ethanol"})

IUPAC_HCL = re.compile(r"(di|tri|tetra)?hydrochloride")
IUPAC_STEREO = re.compile(r"\(\d*[rs](?:,\d*[rs])*\)")
NAME_ANNOTATION = re.compile(
    r"\((?:[^()]*(?:inhibitor|NSC|antagonist|agonist)[^()]*)\)"
)
NAME_COMMA_SALT = re.compile(r", (sodium|potassium) salt")
NAME_SHORT_ALPHA = re.compile(r"\b[a]-[A-Z]")

# The synonym delimiter is ";" with no surrounding space: 194 of the 195 original
# salt records use exactly that, and '"; "' trips the whitespace check.
SYNONYM_DELIMITER = ";"


@dataclass(frozen=True)
class Check:
    """What one check is, independent of any record it runs against."""

    id: str
    title: str
    independent: bool
    severities: tuple[str, ...]


@dataclass(frozen=True)
class Finding:
    """One check's verdict on one record.

    ``cas`` is the join key to waivers, quarantine and the reference tables.
    ``name`` is display text only and must never be joined on.
    """

    check: str
    severity: str
    detail: str
    cas: str = ""
    name: str = ""
    record_index: int = 0
    evidence: str = ""
    independent: bool | None = None
    waiver: str | None = None

    @property
    def is_independent(self) -> bool:
        """Whether this finding compared sources of different origin."""
        if self.independent is not None:
            return self.independent
        return CHECKS[self.check].independent


CHECKS: dict[str, Check] = {}
_RECORD_CHECKS: list[tuple[str, Callable[[RecordContext], Iterator[Finding]]]] = []
_FILE_CHECKS: list[tuple[str, Callable[[FileContext], Iterator[Finding]]]] = []


def _register(
    check_id: str,
    title: str,
    *,
    independent: bool,
    severities: tuple[str, ...],
    scope: str = "record",
) -> Callable[[Callable], Callable]:
    """Declare a check and add its function to the registry."""

    def decorate(func: Callable) -> Callable:
        if check_id in CHECKS:
            raise ValueError(f"check {check_id} is already registered")
        CHECKS[check_id] = Check(
            id=check_id, title=title, independent=independent, severities=severities
        )
        if scope == "record":
            _RECORD_CHECKS.append((check_id, func))
        elif scope == "file":
            _FILE_CHECKS.append((check_id, func))
        elif scope != "declared":
            raise ValueError(f"unknown check scope {scope!r}")
        return func

    return decorate


@dataclass
class RecordContext:
    """One record and everything derived from it that more than one check needs."""

    record: SdfRecord
    structure: Structure
    role: str = ROLE_AUTO

    def __post_init__(self) -> None:
        data = self.record.data
        self.name = self.record.name
        self.cas = self.record.cas
        self.relationship = data.get("RELATIONSHIP", "").strip()
        self.synonym = data.get("SYNONYM")
        self.iupac = data.get("IUPAC_NAME") or ""
        self.name_lower = self.name.lower()
        self.iupac_lower = self.iupac.lower()
        # Vendor code stripped first, so "RS 56812" does not read as (RS).
        cleaned = VENDOR_CODE.sub("", self.name)
        self.specific = bool(SPECIFIC.search(cleaned))
        self.racemic = bool(RACEMIC.search(cleaned))
        self.is_salt = self._resolve_is_salt()

    def _resolve_is_salt(self) -> bool:
        """Whether salt-only checks apply to this record.

        A single input file carries no group context, so by default each record is
        judged on what it is: more than one fragment, or an asserted class. The
        explicit roles exist to reproduce the original two-file behaviour, where one
        file was known to hold salts and the other known not to.

        Deliberately broader than :attr:`has_counterion`: this answers "is this a
        multi-component record", which is the right question for a stoichiometry
        check or a has-part link, and a hydrate is one of those. It is the wrong
        question for "must this record name a class", which is what
        :attr:`has_counterion` is for.
        """
        if self.role == ROLE_SALT:
            return True
        if self.role == ROLE_NEUTRAL:
            return False
        return self.structure.n_frag > 1 or bool(self.relationship)

    @property
    def has_counterion(self) -> bool:
        """Whether a fragment beyond the parent is something other than solvate.

        Solvent of crystallisation is not a counterion, and the class table has no
        code for a hydrate or an ethanolate -- every entry in it names an ion. So a
        record that is a parent plus water has no class it *could* assert, and
        demanding one held it back at ``high`` with no value that would release it.
        A held record is supposed to have a route out.

        Reading the fragments rather than ``is_salt`` also keeps this honest under
        ``--role salt``: the role says which checks apply to the file, not that
        every record in it grew a counterion.
        """
        return any(x not in classes.SOLVATES for x in self.structure.counter)

    @property
    def cas_key(self) -> str:
        """The CAS number normalised, for joining to decisions and reference data.

        Separate from :attr:`cas`, which is the raw string as the file spells it,
        because two orthogonal things were being conflated. INT-04 must complain
        about the *string* -- ``0557-66-4`` is not a CAS Registry Number and ChEBI
        would store it verbatim. A waiver or a quarantine row is about the
        *compound*, and must keep applying while that spelling is being fixed.
        Joining on the raw string meant a record could not match its own decision,
        and the run then reported "matches no record" while the record was sitting
        right there.
        """
        if not self.cas:
            return ""
        from cas_registry import CAS_VALID, classify_cas

        normalised, verdict, _ = classify_cas(self.cas)
        return normalised if verdict == CAS_VALID else self.cas

    def finding(self, check: str, severity: str, detail: str, **kw) -> Finding:
        return Finding(
            check=check,
            severity=severity,
            detail=detail,
            cas=self.cas,
            name=self.name,
            record_index=self.record.index,
            **kw,
        )


@dataclass
class FileContext:
    """Every record in one file, for the checks that compare records with each other."""

    contexts: list[RecordContext]
    raw: bytes


# ------------------------------------------------------------- record integrity


@_register(
    "INT-02",
    "Record structure matches the submission template",
    independent=True,
    severities=(MEDIUM,),
)
def int02_template_shape(ctx: RecordContext) -> Iterator[Finding]:
    record = ctx.record
    if record.title != record.data.get("NAME", ""):
        # Handoff case 15: a rename has to update the molfile title line too, or
        # the record that was just fixed fails this check.
        yield ctx.finding("INT-02", MEDIUM, "mol title differs from NAME")
    extra = [t for t in record.tag_order if t not in EXPECTED_TAGS]
    if extra:
        yield ctx.finding("INT-02", MEDIUM, f"unexpected tags {extra}")
    for tag, value in record.data.items():
        if "\n" in value.strip():
            yield ctx.finding("INT-02", MEDIUM, f"{tag} spans several lines")


@_register(
    "INT-03",
    "Required fields are present and non-empty",
    independent=True,
    severities=(HIGH, MEDIUM),
)
def int03_required_fields(ctx: RecordContext) -> Iterator[Finding]:
    data = ctx.record.data
    for tag in ("NAME", "CAS_NO"):
        if not data.get(tag, "").strip():
            yield ctx.finding("INT-03", HIGH, f"{tag} missing or empty")
    for tag in ("SYNONYM", "IUPAC_NAME"):
        if tag not in data:
            yield ctx.finding("INT-03", MEDIUM, f"{tag} absent")
    if ctx.has_counterion and not ctx.relationship:
        yield ctx.finding(
            "INT-03", HIGH, "salt record with no RELATIONSHIP class asserted"
        )


@_register(
    "INT-04",
    "CAS Registry Number is well formed and its check digit verifies",
    independent=True,
    severities=(HIGH,),
)
def int04_cas_number(ctx: RecordContext) -> Iterator[Finding]:
    """CAS check-digit arithmetic, one of the few checks that owes nothing to a source.

    Delegates to bcp/cas_registry.py, which already carries this repo's CAS
    handling and its tests, rather than keeping a second copy of the arithmetic.
    That module knows failure modes the prototype's four-line ``cas_status`` did
    not: unicode dash mojibake, a value Excel turned into a date, a leading zero,
    a zero-padded check digit, rotated segments.

    But it *classifies for repair*, and this gate must not accept a repairable
    value. ``classify_cas("42971-09-05")`` returns verdict ``valid`` with repair
    ``zero_padded_check_digit``, because the intended number is recoverable. The
    string in the file is still not a CAS Registry Number, and the string in the
    file is what ChEBI would store. So a non-empty repair code is a high finding
    naming the repair, which is also the fix instruction.
    """
    from cas_registry import (
        CAS_INVALID_CHECKSUM,
        CAS_INVALID_FORMAT,
        CAS_MISSING,
        classify_cas,
    )

    raw = ctx.record.data.get("CAS_NO", "")
    normalised, verdict, repair = classify_cas(raw)
    if verdict == CAS_MISSING:
        # INT-03 already reports an absent or empty CAS; saying it twice adds
        # nothing to the record's report and doubles its finding count.
        return
    if verdict == CAS_INVALID_FORMAT:
        yield ctx.finding("INT-04", HIGH, f"CAS {raw!r}: not a CAS Registry Number")
    elif verdict == CAS_INVALID_CHECKSUM:
        yield ctx.finding("INT-04", HIGH, f"CAS {raw}: check digit does not verify")
    elif repair:
        yield ctx.finding(
            "INT-04",
            HIGH,
            f"CAS {raw!r} is malformed ({repair}); the well-formed value is "
            f"{normalised}",
        )


