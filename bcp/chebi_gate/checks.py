@_register(
    "INT-06",
    "File is ASCII with Unix line endings",
    independent=True,
    severities=(HIGH, LOW),
    scope="file",
)
def int06_file_encoding(fctx: FileContext) -> Iterator[Finding]:
    """Attributed to the file, not to a record, so it is reported once.

    The prototype appended these to every record's finding list, which multiplied
    one file-level problem by the record count and held back all 290 records for a
    single stray byte.
    """
    if any(b > 127 for b in fctx.raw):
        yield Finding(
            check="INT-06", severity=HIGH, detail="file contains non-ASCII bytes"
        )
    if b"\r" in fctx.raw:
        yield Finding(check="INT-06", severity=LOW, detail="file has CRLF line endings")


@_register(
    "INT-05",
    "No two records are the same compound",
    independent=True,
    severities=(HIGH,),
    scope="file",
)
def int05_duplicates(fctx: FileContext) -> Iterator[Finding]:
    """Duplicate CAS, name or structure, attributed to every record involved.

    Reported per record rather than once per group so that holding back a record
    is enough to act on it. Records are identified by CAS in the message, because
    a name-keyed message goes stale the moment one of the pair is renamed.
    """
    keys: tuple[tuple[str, Callable[[RecordContext], str | None]], ...] = (
        ("CAS", lambda c: c.cas or None),
        ("NAME", lambda c: c.name.lower() or None),
        ("InChIKey", lambda c: c.structure.inchikey),
    )
    for label, getter in keys:
        groups: dict[str, list[RecordContext]] = defaultdict(list)
        for ctx in fctx.contexts:
            value = getter(ctx)
            if value:
                groups[value].append(ctx)
        for value, members in groups.items():
            if len(members) < 2:
                continue
            for ctx in members:
                others = [
                    f"{o.cas or 'no CAS'} ({o.name})" for o in members if o is not ctx
                ]
                yield ctx.finding(
                    "INT-05",
                    HIGH,
                    f"duplicate {label} {value!r} shared with {others}",
                )


@_register(
    "REL-01",
    "Records sharing a parent skeleton, as relationship candidates",
    independent=True,
    severities=(INFO,),
    scope="file",
)
def rel01_shared_parents(fctx: FileContext) -> Iterator[Finding]:
    """Never holds a record back; it tells a curator which links to consider."""
    groups: dict[str, list[RecordContext]] = defaultdict(list)
    for ctx in fctx.contexts:
        skeleton = ctx.structure.parent_skeleton
        if skeleton:
            groups[skeleton].append(ctx)
    for members in groups.values():
        if len(members) < 2:
            continue
        for ctx in members:
            others = [
                f"{o.cas or 'no CAS'} ({o.name})" for o in members if o is not ctx
            ]
            yield ctx.finding(
                "REL-01",
                INFO,
                f"shares a parent skeleton with {others}; candidate "
                "is-enantiomer-of / has-part relationship",
            )


