# ------------------------------------------------------------------------ runner


def run_record_checks(ctx: RecordContext) -> list[Finding]:
    """Every record-scoped finding for one record."""
    out: list[Finding] = []
    for check_id, func in _RECORD_CHECKS:
        for finding in func(ctx):
            out.append(validate_finding(finding, check_id))
    return out


def run_file_checks(fctx: FileContext) -> list[Finding]:
    """Every file-scoped finding: duplicates, encoding, shared parents."""
    out: list[Finding] = []
    for check_id, func in _FILE_CHECKS:
        for finding in func(fctx):
            out.append(validate_finding(finding, check_id))
    return out


def validate_finding(finding: Finding, emitting_check: str) -> Finding:
    """Assert a finding matches what its check declared it could emit.

    A check that emits a severity it never declared is a bug in the check, and one
    that silently escapes turns into a record cleared or held for a reason nobody
    can look up. CON-01 legitimately emits CON-05, so the emitting function and
    the finding's check ID are allowed to differ.
    """
    check = CHECKS.get(finding.check)
    if check is None:
        raise ValueError(
            f"{emitting_check} emitted a finding for unregistered check "
            f"{finding.check!r}"
        )
    if finding.waiver is not None and finding.severity == INFO:
        # A waiver downgrades to info after validation; re-validating a waived
        # finding must not reject it for a severity its check never declares.
        return finding
    if finding.severity not in check.severities:
        raise ValueError(
            f"{finding.check} emitted severity {finding.severity!r}, "
            f"declared {check.severities}"
        )
    return finding


def worst_severity(findings: list[Finding]) -> str | None:
    """The most serious severity among findings, or None when there are none."""
    if not findings:
        return None
    return min((f.severity for f in findings), key=lambda s: SEVERITY_RANK[s])


def waive(finding: Finding, reason: str, evidence: str) -> Finding:
    """Downgrade a finding to info, keeping it visible with its reason attached.

    A waiver is a written decision that a finding is correct as it stands, so it
    must not hide the finding: the record still reports it, at info level, with the
    reason and evidence that justified the decision.
    """
    return replace(
        finding,
        severity=INFO,
        detail=f"{finding.detail} [WAIVED: {reason}]",
        evidence=evidence or finding.evidence,
        waiver=reason,
    )
