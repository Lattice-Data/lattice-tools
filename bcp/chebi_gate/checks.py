@_register(
    "CON-08",
    "Stoichiometry in the systematic name matches the structure",
    independent=True,
    severities=(HIGH,),
)
def con08_iupac_stoichiometry(ctx: RecordContext) -> Iterator[Finding]:
    if not ctx.structure.parse or not ctx.iupac:
        return
    if not (ctx.is_salt or ctx.role == ROLE_SALT):
        return
    match = IUPAC_HCL.search(ctx.iupac_lower)
    if not match:
        return
    drawn = sum(v for k, v in ctx.structure.frags.items() if k in ("HCl", "Cl-"))
    want = {"di": 2, "tri": 3, "tetra": 4}.get(match.group(1), 1)
    if drawn != want:
        yield ctx.finding(
            "CON-08",
            HIGH,
            f'IUPAC "{match.group(0)}" vs {drawn} HCl in structure',
        )


