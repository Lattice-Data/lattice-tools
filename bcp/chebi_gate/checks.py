"""The check registry: one function per check, each declaring what it is worth.

Every check carries three pieces of metadata beyond its logic:

``severity``
    Which severities it may emit. ``high`` always holds a record back, ``medium``
    holds unless the caller allows it, ``low`` and ``info`` never hold.

``independent``
    Whether the two things being compared have different origins. This is the most
    important field in the module and the reason the registry exists.

    The submission SDFs were generated by asking PubChem about each CAS number, so
    checking those SDFs against PubChem is asking a source to confirm itself. On
    the batch this was ported from, such a check passed 284 of 290 records, and the
    number is close to meaningless -- it mostly says the generation step ran. The
    same batch, checked against evidence of a different origin, showed
    efonidipine missing an ethanol fragment that the circular check had called
    flawless. So the summary reports the two kinds separately and never adds them
    together.

    A few checks are independent or circular *per finding* rather than per check:
    EXT-01 is circular when a CAS number resolved through the PubChem cache and
    independent when it resolved through the CAS registry export. Those set the
    flag on the finding.

``title``
    A plain-English sentence, so a report can say what was checked without the
    reader holding a table of check IDs in their head.

Checks are keyed on the CAS number, never on NAME. NAME is mutable display text:
renaming four records in the prototype silently broke every name-keyed join and
needed a rename map bolted on to paper over it.
"""

