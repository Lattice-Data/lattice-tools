@pytest.fixture
def drawn_key(ctx) -> str:
    return ctx.structure.inchikey


def registry(tmp_path: Path, **row) -> casreg.Registry:
    path = tmp_path / f"reg{len(list(tmp_path.glob('reg*.csv')))}.csv"
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(casreg.REGISTRY_COLUMNS))
        writer.writeheader()
        writer.writerow({**{c: "" for c in casreg.REGISTRY_COLUMNS}, "cas": CAS, **row})
    return casreg.load(path)


def pubchem(tmp_path: Path, name: str, **body) -> Path:
    directory = tmp_path / name
    directory.mkdir()
    payload = {
        "cas": CAS,
        "cids_status": 200,
        "cids": [1],
        "cid": 1,
        "property_status": 200,
        "properties": {"InChIKey": WRONG_KEY, "MolecularFormula": "C2H8ClN"},
        "status": "ok",
    }
    payload.update(body)
    (directory / f"{CAS}.json").write_text(json.dumps(payload))
    return directory


def chebi_index(tmp_path: Path, *rows: tuple[str, str, str]) -> chebi_release.Index:
    release = tmp_path / f"rel{len(list(tmp_path.glob('rel*')))}"
    release.mkdir()
    (release / "structures.tsv").write_text(
        "compound_id\tstandard_inchi_key\n"
        + "".join(f"{cid}\t{key}\n" for cid, key, _ in rows)
    )
    (release / "compounds.tsv").write_text(
        "id\tascii_name\tstars\n"
        + "".join(f"{cid}\t{name}\t3\n" for cid, _, name in rows)
    )
    (release / "database_accession.tsv").write_text(
        "compound_id\taccession_number\ttype\n"
    )
    return chebi_release.distil(release, tmp_path / f"idx{release.name}", generated="x")


def ext01(evidence, ctx) -> list:
    return list(external.ext01(evidence, ctx))


