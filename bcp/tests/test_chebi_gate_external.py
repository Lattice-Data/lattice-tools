def test_a_cas_source_can_confirm_but_never_refute(tmp_path, ctx):
    """Its structure strings are unreliable for salts.

    Measured on the batch: treating the SciFinder InChIKey as authoritative turns
    25 sound records into high findings -- 7-NINA sodium salt is registered as the
    neutral acid plus Na against an ionic drawing, AY 9944 carries a pre-standard
    "InChI=1/" key with the same skeleton, cyanopindolol hemifumarate is registered
    as "1/2C4H4O4" against a doubled drawing. None is a defect.
    """
    evidence = external.Evidence(registry=registry(tmp_path, inchikey=WRONG_KEY))
    verdict = external.resolve_cas(evidence, ctx)
    assert verdict.status == external.UNRESOLVED
    assert not [f for f in ext01(evidence, ctx) if f.severity == HIGH]


