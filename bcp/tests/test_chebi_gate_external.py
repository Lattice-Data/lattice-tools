from chebi_gate.checks import HIGH, INFO, LOW, MEDIUM
from tests.chebi_gate_helpers import ISA_HYDROCHLORIDE, salt_record, sdf_bytes

CAS = "557-66-4"
WRONG_KEY = "ZZZZZZZZZZZZZZ-ZZZZZZZZZZ-Z"


