"""The external checks, and the independent-versus-circular accounting they carry.

This is the module the package calls its most important idea, and it had no test
file at all until an adversarial review pointed that out: EXT-02 and EXT-04 could
be deleted outright and the suite stayed green.

The distinction being pinned here is not a style preference. The submission SDFs
were generated by asking PubChem about each CAS number, so a PubChem agreement is
a source confirming itself. On the reference batch that "confirmed" 284 of 290
records; measured properly, only 259 are corroborated by a source of a different
origin and 31 rest entirely on PubChem.
"""

from __future__ import annotations

