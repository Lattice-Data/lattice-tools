def test_a_solvated_hydrohalide_still_satisfies_its_class():
    """A hydrated hydrochloride is a hydrochloride.

    The class rule demanded that *every* counterion be a halide, so any hydrate or
    ethanolate of a hydrohalide could never satisfy CON-01. Efonidipine
    hydrochloride monoethanolate is exactly that shape.
    """
    from chebi_gate import classes

    record = sdf.parse_bytes(
        sdf_bytes(
            salt_record(
                name="decylamine hydrochloride hydrate",
                mol="amine_hydrate",
                relationship=ISA_HYDROCHLORIDE,
                iupac="x",
            )
        )
    ).records[0]
    hydrate_only = structure.analyse(record)
    assert hydrate_only.counter == ["H2O"]
    # Water alone is not a hydrohalide: there is no halide to satisfy the class.
    assert classes.class_supported("hydrochloride", hydrate_only) is False

    from dataclasses import replace

    with_both = replace(hydrate_only, counter=["HCl", "H2O"])
    assert classes.class_supported("hydrochloride", with_both) is True, (
        "the water must not disqualify the hydrochloride"
    )
    assert classes.SOLVATES == ("H2O", "C2H6O")


